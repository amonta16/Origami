"""
phone_time_donut.py — "Average time spent on the phone per day" donut animation, built and rendered in Blender.

Four arc segments (Gen Z, Millennials, Gen X, Boomers) sweep open one after another, each thickening to a
radius proportional to its value while its label counts up, and the whole ring spins and settles into place.
Everything is generated by this script: there are no external assets.

Two modes:
  loop  (default) — the finished chart is on screen the whole time; the ring turns once per cycle while the
                    segments swell one after another and their labels pop. First and last frames join, so it
                    repeats like a GIF.
  intro           — the build-in: segments sweep open one by one with count-up labels while the ring spins in.

Run headless (Blender 4.2 or newer; tested on 5.3):
  blender -b -P phone_time_donut.py -- --out <dir> --render                          # loop MP4
  blender -b -P phone_time_donut.py -- --out <dir> --mode intro --render             # intro MP4
  blender -b -P phone_time_donut.py -- --out <dir> --stills 1,60,120,300             # PNG test frames
  blender -b -P phone_time_donut.py -- --out <dir> --engine cycles --render

The script is also embedded in the saved .blend (Text editor, "Register" on) so that scrubbing the timeline in
the Blender UI works when "Auto Run Python Scripts" is allowed. Data: reviews.org (as in the reference still).
"""
import bpy
import os
import sys
from math import radians, cos, sin, ceil, pi

# ---------------------------------------------------------------- settings
FPS = 30
FRAME_END = 300                 # intro: 10 s
RES = (1920, 1080)
ORTHO_SCALE = 8.3               # intro camera frame width in scene units

# loop mode
LOOP_FRAMES = 360               # 12 s per cycle: one full turn of the ring
PULSE_LEN = 90                  # each segment swells for 3 s, one after another (4 x 90 = 360)
PULSE_AMOUNT = 0.15             # thickness grows by this fraction at the peak
PULSE_LABEL_SCALE = 0.14        # the label pops by this fraction at the peak
LABEL_CLEAR = 0.55              # gap between a segment's outer edge and its orbiting label
LOOP_ORTHO_SCALE = 10.8         # wider frame so orbiting labels never leave it
LOOP_MAX_THICK = 0.90

R_IN = 1.0                      # hole radius
MAX_THICK = 0.95                # thickness of the biggest segment
GAP_DEG = 1.6                   # half-gap between segments (degrees)

SPIN_START_DEG = -360.0         # the ring starts one full turn behind and eases into place
SPIN_END_FRAME = 240
SPIN_POWER = 6                  # higher = faster start, longer settle
LABEL_SWING = 0.5               # labels follow the spin at this fraction of the ring's angle, so they stay in frame

SEG_LEN = 60                    # frames each segment takes to sweep open
SEG_STEP = 54                   # frames between segment starts (6-frame overlap)
LABEL_IN = 24                   # label fades in this many frames after its segment starts
LABEL_FADE = 20
UNDERLINE_IN = 30
UNDERLINE_LEN = 24

SEGMENTS = [
    dict(key="genz", name="Generation Z", minutes=378,
         c0="#D86CB8", c1="#FF2458", value_col="#FF2E6E", name_col="#FF6A9A",
         side=1, anchor=(1.85, 1.20)),
    dict(key="mill", name="Millennials", minutes=362,
         c0="#5A10FF", c1="#C026A6", value_col="#7A4CFF", name_col="#9F80FF",
         side=1, anchor=(1.80, -1.15)),
    dict(key="genx", name="Generation X", minutes=294,
         c0="#B49AF0", c1="#8656FF", value_col="#B8A4F6", name_col="#CCBEF8",
         side=-1, anchor=(-1.85, -0.90)),
    dict(key="boom", name="Boomers", minutes=198,
         c0="#EDE4FC", c1="#D6C6F8", value_col="#DCD0F8", name_col="#E8E0FA",
         side=-1, anchor=(-1.45, 1.10)),
]

_total = sum(s["minutes"] for s in SEGMENTS)
_start = 100.0                  # Gen Z begins just left of 12 o'clock and the ring fills clockwise
for _i, _s in enumerate(SEGMENTS):
    _s["span"] = 360.0 * _s["minutes"] / _total
    _s["start"] = _start
    _start -= _s["span"]
    _s["thick"] = MAX_THICK * _s["minutes"] / SEGMENTS[0]["minutes"]
    _s["f0"] = 6 + _i * SEG_STEP
    _s["f1"] = _s["f0"] + SEG_LEN

CENTER_LINES = [  # (text, font role, color, size, baseline y)
    ("AVERAGE", "italic", "#C9C9C9", 0.235, 0.39),
    ("TIME SPENT", "italic", "#FF2A6A", 0.255, 0.10),
    ("ON THE PHONE", "mixed", "#F4F4F4", 0.235, -0.19),
    ("PER DAY", "italic", "#C9C9C9", 0.235, -0.48),
]
CENTER_FADE_START = 14
SOURCE_FADE_START = 232

FONT_DIR = os.path.join(os.environ.get("WINDIR", "C:\\Windows"), "Fonts")
FONT_CANDIDATES = {
    "italic": ["seguisbi.ttf", "segoeuiz.ttf", "arialbi.ttf"],   # semibold italic
    "bold": ["seguisb.ttf", "segoeuib.ttf", "arialbd.ttf"],      # semibold / bold upright
    "heavy": ["segoeuib.ttf", "seguisb.ttf", "arialbd.ttf"],     # bold for the numbers
    "regular": ["segoeui.ttf", "arial.ttf"],
}

# ---------------------------------------------------------------- helpers
def hex2lin(h):
    h = h.lstrip("#")
    def s2l(c):
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    return tuple(s2l(int(h[i:i + 2], 16) / 255.0) for i in (0, 2, 4))

def lerp(a, b, t):
    return a + (b - a) * t

def clamp01(x):
    return 0.0 if x < 0.0 else 1.0 if x > 1.0 else x

def ease_out_quart(t):
    t = clamp01(t)
    return 1.0 - (1.0 - t) ** 4

def ease_out_cubic(t):
    t = clamp01(t)
    return 1.0 - (1.0 - t) ** 3

def ease_out_back(t, c1=1.1):
    t = clamp01(t)
    c3 = c1 + 1.0
    return 1.0 + c3 * (t - 1.0) ** 3 + c1 * (t - 1.0) ** 2

def spin_angle(frame):
    p = clamp01((frame - 1) / float(SPIN_END_FRAME - 1))
    return SPIN_START_DEG * (1.0 - p) ** SPIN_POWER

def pulse(frame, index):
    """0..1 bump for segment `index` in loop mode; segments take turns, and the cycle repeats every LOOP_FRAMES."""
    ph = ((frame - 1 - index * PULSE_LEN) % LOOP_FRAMES) / float(PULSE_LEN)
    if ph >= 1.0:
        return 0.0
    return sin(pi * ph) ** 2

def load_font(role):
    for name in FONT_CANDIDATES[role]:
        path = os.path.join(FONT_DIR, name)
        if os.path.exists(path):
            try:
                return bpy.data.fonts.load(path, check_existing=True)
            except Exception:
                pass
    return bpy.data.fonts.get("Bfont Regular") or bpy.data.fonts.get("Bfont")

def set_blended(mat):
    if hasattr(mat, "surface_render_method"):
        mat.surface_render_method = "BLENDED"
    elif hasattr(mat, "blend_method"):
        mat.blend_method = "BLEND"
    for attr, val in (("shadow_method", "NONE"), ("use_backface_culling", False)):
        try:
            setattr(mat, attr, val)
        except Exception:
            pass

def new_material(name):
    mat = bpy.data.materials.new(name)
    try:
        mat.use_nodes = True
    except Exception:
        pass
    nt = mat.node_tree
    nt.nodes.clear()
    return mat, nt

# ---------------------------------------------------------------- materials
def mat_segment():
    """Flat emission colored by the per-vertex gradient."""
    mat, nt = new_material("Segment")
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    em = nt.nodes.new("ShaderNodeEmission")
    em.inputs["Strength"].default_value = 1.0
    vc = nt.nodes.new("ShaderNodeVertexColor")
    vc.layer_name = "Col"
    nt.links.new(vc.outputs["Color"], em.inputs["Color"])
    nt.links.new(em.outputs["Emission"], out.inputs["Surface"])
    return mat

def mat_object_color(name, fixed_rgb=None, vertex_alpha=False):
    """Emission that takes its color (or only its alpha) from the object color, so fades are plain keyframes."""
    mat, nt = new_material(name)
    set_blended(mat)
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    mix = nt.nodes.new("ShaderNodeMixShader")
    tr = nt.nodes.new("ShaderNodeBsdfTransparent")
    em = nt.nodes.new("ShaderNodeEmission")
    oi = nt.nodes.new("ShaderNodeObjectInfo")
    if fixed_rgb is None:
        nt.links.new(oi.outputs["Color"], em.inputs["Color"])
    else:
        em.inputs["Color"].default_value = (*hex2lin(fixed_rgb), 1.0)
    alpha = oi.outputs["Alpha"]
    if vertex_alpha:
        vc = nt.nodes.new("ShaderNodeVertexColor")
        vc.layer_name = "Col"
        mul = nt.nodes.new("ShaderNodeMath")
        mul.operation = "MULTIPLY"
        nt.links.new(alpha, mul.inputs[0])
        nt.links.new(vc.outputs["Alpha"], mul.inputs[1])
        alpha = mul.outputs[0]
    nt.links.new(alpha, mix.inputs["Fac"])
    nt.links.new(tr.outputs[0], mix.inputs[1])
    nt.links.new(em.outputs[0], mix.inputs[2])
    nt.links.new(mix.outputs[0], out.inputs["Surface"])
    return mat

def mat_background():
    """Near-black backdrop with a soft lighter pool behind the ring, offset up-left like the reference."""
    mat, nt = new_material("Backdrop")
    out = nt.nodes.new("ShaderNodeOutputMaterial")
    em = nt.nodes.new("ShaderNodeEmission")
    tc = nt.nodes.new("ShaderNodeTexCoord")
    mp = nt.nodes.new("ShaderNodeMapping")
    scale = 0.27
    center = (-0.7, 0.45)
    mp.inputs["Scale"].default_value = (scale, scale, scale)
    mp.inputs["Location"].default_value = (-scale * center[0], -scale * center[1], 0.0)
    gr = nt.nodes.new("ShaderNodeTexGradient")
    gr.gradient_type = "SPHERICAL"
    ramp = nt.nodes.new("ShaderNodeValToRGB")
    ramp.color_ramp.interpolation = "EASE"
    ramp.color_ramp.elements[0].position = 0.0
    ramp.color_ramp.elements[0].color = (*hex2lin("#020202"), 1.0)
    ramp.color_ramp.elements[1].position = 1.0
    ramp.color_ramp.elements[1].color = (*hex2lin("#232325"), 1.0)
    nt.links.new(tc.outputs["Object"], mp.inputs["Vector"])
    nt.links.new(mp.outputs["Vector"], gr.inputs["Vector"])
    nt.links.new(gr.outputs["Fac"], ramp.inputs["Fac"])
    nt.links.new(ramp.outputs["Color"], em.inputs["Color"])
    nt.links.new(em.outputs["Emission"], out.inputs["Surface"])
    return mat

# ---------------------------------------------------------------- geometry
def build_segment_mesh(mesh, seg, t, thick_mult=1.0, max_thick=MAX_THICK):
    """Rebuild one arc for progress t in [0, 1]: sweep eases open, thickness grows with a little overshoot.
    thick_mult scales the final thickness (used for the loop-mode pulse). Returns the outer radius."""
    mesh.clear_geometry()
    for ca in list(mesh.color_attributes):
        mesh.color_attributes.remove(ca)
    if t <= 0.0:
        mesh.update()
        return R_IN
    span = seg["span"] - 2.0 * GAP_DEG
    sweep = max(span * ease_out_quart(t), 0.05)
    base = max_thick * seg["minutes"] / SEGMENTS[0]["minutes"]
    thick = base * (0.12 + 0.88 * ease_out_back(t)) * thick_mult
    r_out = R_IN + thick
    a_start = seg["start"] - GAP_DEG
    n = max(2, int(ceil(sweep / 0.75)) + 1)
    c0, c1 = hex2lin(seg["c0"]), hex2lin(seg["c1"])
    verts, cols = [], []
    for i in range(n):
        d = sweep * i / (n - 1)
        a = radians(a_start - d)                     # clockwise
        u = d / span                                 # gradient stays pinned to the geometry
        col = tuple(lerp(c0[k], c1[k], u) for k in range(3))
        ca, sa = cos(a), sin(a)
        verts.append((R_IN * ca, R_IN * sa, 0.0))
        verts.append((r_out * ca, r_out * sa, 0.0))
        inner = tuple(c * 0.93 for c in col)         # a touch darker toward the hole
        cols.append((*inner, 1.0))
        cols.append((*col, 1.0))
    faces = [(2 * i, 2 * i + 1, 2 * i + 3, 2 * i + 2) for i in range(n - 1)]
    mesh.from_pydata(verts, [], faces)
    attr = mesh.color_attributes.new("Col", "FLOAT_COLOR", "POINT")
    attr.data.foreach_set("color", [c for col in cols for c in col])
    mesh.update()
    return r_out

def make_underline(name, side, mat, parent, loc, centered=False):
    """Thin bar under the label. Intro: solid under the text, fading on the end that points at the ring.
    Loop (centered): symmetric, fading out at both ends."""
    h = 0.016
    if centered:
        xs = [(-0.5, 0.0), (0.0, 1.0), (0.5, 0.0)]
    else:
        length, tail = 0.80, 0.30
        xs = [(-tail, 0.0), (0.0, 1.0), (length, 1.0)]
    verts, cols = [], []
    for x, a in xs:
        verts.append((side * x, -h / 2, 0.0))
        verts.append((side * x, h / 2, 0.0))
        cols.extend([(1.0, 1.0, 1.0, a), (1.0, 1.0, 1.0, a)])
    faces = [(0, 1, 3, 2), (2, 3, 5, 4)]
    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(verts, [], faces)
    attr = mesh.color_attributes.new("Col", "FLOAT_COLOR", "POINT")
    attr.data.foreach_set("color", [c for col in cols for c in col])
    mesh.update()
    ob = bpy.data.objects.new(name, mesh)
    ob.data.materials.append(mat)
    ob.parent = parent
    ob.location = loc
    return ob

def make_text(name, body, size, font, mat, color_hex, align="LEFT", loc=(0, 0, 0), parent=None,
              spacing=1.0):
    cu = bpy.data.curves.new(name, "FONT")
    cu.body = body
    cu.size = size
    cu.align_x = align
    cu.space_character = spacing
    if font:
        cu.font = font
    cu.materials.append(mat)
    ob = bpy.data.objects.new(name, cu)
    ob.color = (*hex2lin(color_hex), 1.0)
    ob.location = loc
    ob.parent = parent
    return ob

def key_alpha(ob, f_in, f_out, a0=0.0, a1=1.0):
    ob.color[3] = a0
    ob.keyframe_insert(data_path="color", index=3, frame=f_in)
    ob.color[3] = a1
    ob.keyframe_insert(data_path="color", index=3, frame=f_out)

def key_scale(ob, f_in, f_out, s0, s1):
    ob.scale = (s0, s0, s0)
    ob.keyframe_insert(data_path="scale", frame=f_in)
    ob.scale = (s1, s1, s1)
    ob.keyframe_insert(data_path="scale", frame=f_out)

# ---------------------------------------------------------------- scene
def build_scene(mode):
    scene = bpy.context.scene
    loop = mode == "loop"
    # start from an empty scene
    for ob in list(scene.objects):
        bpy.data.objects.remove(ob, do_unlink=True)
    link = scene.collection.objects.link

    scene.render.resolution_x, scene.render.resolution_y = RES
    scene.render.resolution_percentage = 100
    scene.render.fps = FPS
    scene.frame_start, scene.frame_end = 1, (LOOP_FRAMES if loop else FRAME_END)
    scene.view_settings.view_transform = "Standard"
    try:
        scene.view_settings.look = "None"
    except Exception:
        pass
    scene.render.film_transparent = False

    world = bpy.data.worlds.new("Black")
    try:
        world.use_nodes = True
    except Exception:
        pass
    try:
        bg = world.node_tree.nodes["Background"]
        bg.inputs["Color"].default_value = (0, 0, 0, 1)
        bg.inputs["Strength"].default_value = 0.0
    except Exception:
        world.color = (0, 0, 0)
    scene.world = world

    # camera: straight down, orthographic, 16:9 frame centered on the ring
    cam_data = bpy.data.cameras.new("Camera")
    cam_data.type = "ORTHO"
    cam_data.ortho_scale = LOOP_ORTHO_SCALE if loop else ORTHO_SCALE
    cam = bpy.data.objects.new("Camera", cam_data)
    cam.location = (0, 0, 10)
    link(cam)
    scene.camera = cam

    # backdrop
    bg_mesh = bpy.data.meshes.new("Backdrop")
    bg_mesh.from_pydata([(-12, -12, 0), (12, -12, 0), (12, 12, 0), (-12, 12, 0)], [], [(0, 1, 2, 3)])
    bg_mesh.update()
    bg_ob = bpy.data.objects.new("Backdrop", bg_mesh)
    bg_ob.location = (0, 0, -1)
    bg_ob.data.materials.append(mat_background())
    link(bg_ob)

    fonts = {role: load_font(role) for role in FONT_CANDIDATES}
    seg_mat = mat_segment()
    text_mat = mat_object_color("TextObjColor")
    line_mat = mat_object_color("Underline", vertex_alpha=True)

    # the ring: an empty that spins, with one mesh object per segment
    ring = bpy.data.objects.new("RingRoot", None)
    link(ring)
    for seg in SEGMENTS:
        mesh = bpy.data.meshes.new("Seg_" + seg["key"])
        ob = bpy.data.objects.new("Seg_" + seg["key"], mesh)
        ob.data.materials.append(seg_mat)
        ob.parent = ring
        link(ob)

        # label group: an empty the handler moves along the spin arc; the text inside stays upright
        emp = bpy.data.objects.new("Label_" + seg["key"], None)
        link(emp)
        if loop:
            # centered block that orbits just outside its own segment
            m, mm = seg["minutes"] // 60, seg["minutes"] % 60
            val = make_text("Val_" + seg["key"], "%dh %dm" % (m, mm), 0.36, fonts["heavy"], text_mat,
                            seg["value_col"], align="CENTER", loc=(0, 0.10, 0.02), parent=emp)
            nm = make_text("Name_" + seg["key"], seg["name"], 0.19, fonts["regular"], text_mat, seg["name_col"],
                           align="CENTER", loc=(0, -0.20, 0.02), parent=emp)
            ul = make_underline("Line_" + seg["key"], 1, line_mat, emp, (0, -0.31, 0.01), centered=True)
            ul.color = (*hex2lin(seg["name_col"]), 1.0)
            for o in (val, nm, ul):
                link(o)
            continue
        align = "LEFT" if seg["side"] > 0 else "RIGHT"
        val = make_text("Val_" + seg["key"], "0h 0m", 0.36, fonts["heavy"], text_mat, seg["value_col"],
                        align=align, loc=(0, 0, 0.02), parent=emp)
        nm = make_text("Name_" + seg["key"], seg["name"], 0.19, fonts["regular"], text_mat, seg["name_col"],
                       align=align, loc=(0, -0.30, 0.02), parent=emp)
        ul = make_underline("Line_" + seg["key"], seg["side"], line_mat, emp, (0, -0.41, 0.01))
        ul.color = (*hex2lin(seg["name_col"]), 1.0)
        for o in (val, nm, ul):
            link(o)
        fa = seg["f0"] + LABEL_IN
        key_alpha(val, fa, fa + LABEL_FADE)
        key_alpha(nm, fa + 4, fa + 4 + LABEL_FADE)
        key_alpha(ul, fa + 2, fa + 2 + LABEL_FADE)
        ul.scale = (0.0, 1.0, 1.0)
        ul.keyframe_insert(data_path="scale", index=0, frame=seg["f0"] + UNDERLINE_IN)
        ul.scale = (1.0, 1.0, 1.0)
        ul.keyframe_insert(data_path="scale", index=0, frame=seg["f0"] + UNDERLINE_IN + UNDERLINE_LEN)

    # center copy
    gray_fixed = mat_object_color("CenterGrayFixed", fixed_rgb="#CFCFCF")
    for i, (body, role, col, size, y) in enumerate(CENTER_LINES):
        if role == "mixed":
            ob = make_text("Center_%d" % i, body, size, fonts["italic"], text_mat, col, align="CENTER",
                           loc=(0, y, 0.02), spacing=0.97)
            cu = ob.data
            cu.font_bold = fonts["bold"]
            cu.materials.append(gray_fixed)
            split = body.index(" PHONE")
            for ci in range(len(body)):
                fmt = cu.body_format[ci]
                if ci < split:
                    fmt.use_bold = True           # "ON THE" upright white
                else:
                    fmt.material_index = 1        # "PHONE" italic gray
        else:
            ob = make_text("Center_%d" % i, body, size, fonts[role], text_mat, col, align="CENTER",
                           loc=(0, y, 0.02), spacing=0.97)
        link(ob)
        if not loop:
            f0 = CENTER_FADE_START + i * 5
            key_alpha(ob, f0, f0 + 26)
            key_scale(ob, f0, f0 + 26, 0.92, 1.0)

    half_w = (LOOP_ORTHO_SCALE if loop else ORTHO_SCALE) / 2.0
    half_h = half_w * RES[1] / RES[0]
    src = make_text("Source", "SOURCE: REVIEWS.ORG", 0.13 * (1.3 if loop else 1.0), fonts["heavy"], text_mat,
                    "#F0F0F0", align="RIGHT", loc=(half_w - 0.2, -half_h + 0.21, 0.02))
    link(src)
    if not loop:
        key_alpha(src, SOURCE_FADE_START, SOURCE_FADE_START + 20)

    # smoother fades: ease the keyframes we just inserted
    for ob in scene.objects:
        ad = ob.animation_data
        if ad and ad.action:
            try:
                for fc in ad.action.fcurves:
                    for kp in fc.keyframe_points:
                        kp.interpolation = "BEZIER"
                        kp.easing = "EASE_IN_OUT"
            except Exception:
                pass

    scene["donut_built"] = True
    scene["donut_mode"] = mode

# ---------------------------------------------------------------- per-frame update
def loop_update(scene, f):
    """Seamless cycle: constant clockwise spin, one segment swelling at a time, labels riding along upright."""
    ring = bpy.data.objects.get("RingRoot")
    if ring is None:
        return
    th = -360.0 * ((f - 1) % LOOP_FRAMES) / float(LOOP_FRAMES)
    ring.rotation_euler.z = radians(th)
    for i, seg in enumerate(SEGMENTS):
        b = pulse(f, i)
        ob = bpy.data.objects.get("Seg_" + seg["key"])
        r_out = R_IN
        if ob is not None:
            r_out = build_segment_mesh(ob.data, seg, 1.0, thick_mult=1.0 + PULSE_AMOUNT * b,
                                       max_thick=LOOP_MAX_THICK)
        emp = bpy.data.objects.get("Label_" + seg["key"])
        if emp is not None:
            a = radians(seg["start"] - seg["span"] / 2.0 + th)      # the segment's middle, in world space
            r = r_out + LABEL_CLEAR
            emp.location = (r * cos(a), r * sin(a), 0.0)
            k = 1.0 + PULSE_LABEL_SCALE * b
            emp.scale = (k, k, k)
        val = bpy.data.objects.get("Val_" + seg["key"])
        if val is not None:
            base = hex2lin(seg["value_col"])
            val.color = (*[lerp(cc, 1.0, 0.35 * b) for cc in base], 1.0)   # brightens toward white at the peak

def donut_update(scene, *args):
    f = scene.frame_current
    if scene.get("donut_mode", "loop") == "loop":
        loop_update(scene, f)
        return
    th = spin_angle(f)
    ring = bpy.data.objects.get("RingRoot")
    if ring is None:
        return
    ring.rotation_euler.z = radians(th)
    c, s = cos(radians(th * LABEL_SWING)), sin(radians(th * LABEL_SWING))
    for seg in SEGMENTS:
        ob = bpy.data.objects.get("Seg_" + seg["key"])
        if ob is not None:
            t = (f - seg["f0"]) / float(seg["f1"] - seg["f0"])
            build_segment_mesh(ob.data, seg, clamp01(t))
        emp = bpy.data.objects.get("Label_" + seg["key"])
        if emp is not None:
            ax, ay = seg["anchor"]
            emp.location = (ax * c - ay * s, ax * s + ay * c, 0.0)
        val = bpy.data.objects.get("Val_" + seg["key"])
        if val is not None:
            fa = seg["f0"] + LABEL_IN
            tc = clamp01((f - fa) / float(seg["f1"] - fa))
            mins = int(round(seg["minutes"] * ease_out_cubic(tc)))
            val.data.body = "%dh %dm" % (mins // 60, mins % 60)

try:
    _persistent = bpy.app.handlers.persistent
except AttributeError:  # very old Blender
    def _persistent(fn):
        return fn

@_persistent
def _donut_handler(scene, *args):
    donut_update(scene, *args)

def register_handler():
    hs = bpy.app.handlers.frame_change_pre
    for h in list(hs):
        if getattr(h, "__name__", "") == "_donut_handler":
            hs.remove(h)
    hs.append(_donut_handler)

# ---------------------------------------------------------------- render
def set_engine(scene, engine):
    if engine == "cycles":
        scene.render.engine = "CYCLES"
        scene.cycles.samples = 16
        scene.cycles.use_denoising = False
        try:
            scene.cycles.max_bounces = 0
        except Exception:
            pass
        return
    for eid in ("BLENDER_EEVEE_NEXT", "BLENDER_EEVEE"):
        try:
            scene.render.engine = eid
            break
        except TypeError:
            continue
    try:
        scene.eevee.taa_render_samples = 32
    except Exception:
        pass

def render_stills(scene, out_dir, frames):
    scene.render.image_settings.file_format = "PNG"
    scene.render.image_settings.color_mode = "RGB"
    for f in frames:
        scene.frame_set(f)
        scene.render.filepath = os.path.join(out_dir, "frame_%04d.png" % f)
        bpy.ops.render.render(write_still=True)
        print("wrote", scene.render.filepath)

def render_movie(scene, out_dir, name):
    r = scene.render
    if hasattr(r.image_settings, "media_type"):   # Blender 5.x: video is a media type of its own
        r.image_settings.media_type = "VIDEO"
    r.image_settings.file_format = "FFMPEG"
    r.ffmpeg.format = "MPEG4"
    r.ffmpeg.codec = "H264"
    r.ffmpeg.constant_rate_factor = "HIGH"
    r.ffmpeg.ffmpeg_preset = "GOOD"
    r.filepath = os.path.join(out_dir, name)
    bpy.ops.render.render(animation=True)
    # Blender appends the frame range to movie names; rename to the plain name
    produced = os.path.join(out_dir, "%s%04d-%04d.mp4" % (name, scene.frame_start, scene.frame_end))
    final = os.path.join(out_dir, name + ".mp4")
    if os.path.exists(produced):
        if os.path.exists(final):
            os.remove(final)
        os.rename(produced, final)
        print("wrote", final)

def embed_self():
    """Keep a copy of this script inside the .blend, registered to run on load so scrubbing works in the UI."""
    try:
        path = __file__
    except NameError:
        return
    try:
        src = open(path, encoding="utf-8").read()
    except OSError:
        return
    txt = bpy.data.texts.get("phone_time_donut.py") or bpy.data.texts.new("phone_time_donut.py")
    txt.clear()
    txt.write(src)
    txt.use_module = True

def main():
    argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    opts = {"--out": None, "--stills": None, "--engine": "eevee", "--name": None, "--mode": "loop"}
    render = False
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--render":
            render = True
        elif a in opts and i + 1 < len(argv):
            opts[a] = argv[i + 1]
            i += 1
        i += 1

    mode = opts["--mode"] if opts["--mode"] in ("loop", "intro") else "loop"
    name = opts["--name"] or ("phone_time_donut_loop" if mode == "loop" else "phone_time_donut_intro")

    scene = bpy.context.scene
    if not scene.get("donut_built"):
        build_scene(mode)
    register_handler()
    scene.frame_set(1)

    out_dir = opts["--out"]
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
        set_engine(scene, opts["--engine"])
        embed_self()
        bpy.ops.wm.save_as_mainfile(filepath=os.path.join(out_dir, name + ".blend"))
        if opts["--stills"]:
            render_stills(scene, out_dir, [int(x) for x in opts["--stills"].split(",") if x.strip()])
        if render:
            render_movie(scene, out_dir, name)

main()
